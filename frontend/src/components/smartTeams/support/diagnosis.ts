// What is actually wrong with one person's Smart Teams profile.
//
// WHY THIS IS A MODULE AND NOT JSX
// -------------------------------
// The support screen reads four endpoints and could simply print all four. That
// would be a worse tool than the curl it replaces: the question a support admin
// arrives with is "why is their guide stuck", and the answer lives in the JOIN
// across those payloads — an interview that completed but has no profile, a
// guide row that has said `pending` for three days, an upload waiting on a
// consent support is not allowed to give. Nobody should have to reconstruct
// that from four JSON blobs at the moment somebody is on the phone.
//
// So the rules live here, as pure functions over the API types, with no React
// and no imports that pull any in. Same shape as `interviewFlow.ts`, and for the
// same reason: it means `diagnosis.test.ts` can run under `node --test` with
// Node's own TypeScript stripping, and the repo needs no test runner it does not
// already have.
//
//   cd <repo>/frontend && node --test "src/components/smartTeams/**/*.test.ts"
//
// THE ONE RULE EVERY FINDING FOLLOWS
// ----------------------------------
// A finding says what is true and who it is waiting on. It never says "click
// here to fix it", because for half of these the answer is that support CANNOT
// fix it: approving a guide and confirming a merge are consent, and consent is
// the one thing a support admin is deliberately not given. A tool that suggests
// otherwise teaches the wrong instinct about the whole feature.
import { parseInstant } from '../../../utils/datetime.ts';
import type {
    GuideDocument,
    ProfileSummary,
    ResumeState,
    UploadRecord,
} from '../../../api/smartTeams';

/** How a finding reads, worst first. `blocked` means something broke and will
 *  not un-break itself; `waiting` means the system is correctly waiting on a
 *  person, which is not a fault and must never be styled as one. */
export type FindingTone = 'blocked' | 'attention' | 'waiting' | 'ok';

export interface Finding {
    /** Stable across renders — used as the React key. */
    id: string;
    tone: FindingTone;
    title: string;
    detail: string;
    /** Who the ball is with. `them` is the load-bearing one: it is the answer
     *  to "can you just push it through for me?", which is no. */
    owner: 'system' | 'them' | 'support' | null;
}

/** The interview support read, whose never-started branch has almost no fields.
 *  Typed as a union rather than `Partial<ResumeState>` so a narrowing check is
 *  required before touching `progress` — reading it off the not-started shape is
 *  exactly the bug the API header warns about. */
export type SupportInterview =
    | ({ status: 'not_started'; subject_email: string })
    | (ResumeState & { subject_email: string; profile: ProfileSummary | null });

export interface DiagnosisInput {
    /** `null` when that read failed; a failed read is reported by the page, not
     *  silently diagnosed as an absence. */
    interview: SupportInterview | null;
    guides: GuideDocument[] | null;
    uploads: UploadRecord[] | null;
    /** Suggestions the person has not answered yet. */
    pendingSuggestions: number | null;
    /** Injected so the tests are not clock-dependent. */
    now: Date;
}

// ── Time ─────────────────────────────────────────────────────────────────────

const DAY_MS = 86_400_000;

/** Whole days between an ISO timestamp and `now`, or `null` if unparseable.
 *
 *  Returns `null` rather than 0 for a bad value: "0 days ago" and "we cannot
 *  tell" look identical on screen and mean opposite things when you are trying
 *  to decide whether a job is hung. */
export function daysSince(iso: string | null | undefined, now: Date): number | null {
    const then = parseInstant(iso);
    if (!then) return null;
    return Math.floor((now.getTime() - then.getTime()) / DAY_MS);
}

/** "today" / "yesterday" / "6 days ago". */
export function agoLabel(days: number | null): string {
    if (days === null) return 'at an unknown time';
    if (days <= 0) return 'today';
    if (days === 1) return 'yesterday';
    return `${days} days ago`;
}

/** A generate is dispatched to cubie-worker and the row stays `pending` until
 *  the job writes back. There is no `running` state and no failure column, so
 *  "hung" can only ever be a judgement about AGE — the same age-only reading
 *  `ScoringPhase.delayed` makes, and named as a guess on screen for that reason.
 *
 *  One day, not minutes: a guide is generated by an LLM behind a Cloud Run Job
 *  that queues, and calling a twenty-minute queue a failure would send an admin
 *  chasing jobs that were about to land. */
export const STUCK_AFTER_DAYS = 1;

/** An interview nobody has touched in this long has been abandoned in practice,
 *  whatever the row says. Two weeks rather than a few days because the interview
 *  is ~30 minutes of work people legitimately do across more than one sitting. */
export const STALLED_AFTER_DAYS = 14;

// ── Guides ───────────────────────────────────────────────────────────────────

/** The row a person's guide state actually turns on.
 *
 *  The support read returns EVERY generation, newest first, drafts and failures
 *  included. "Their guide" is the published one if there is one — a published
 *  row is the one the company can see, and a later failed retry does not
 *  un-publish it — and otherwise the newest row. Taking `guides[0]` blindly
 *  reports a failed regeneration as though their live guide were broken. */
export function currentGuide(guides: GuideDocument[]): GuideDocument | null {
    if (!guides.length) return null;
    return guides.find(g => g.published) ?? guides[0];
}

// ── The rules ────────────────────────────────────────────────────────────────

function interviewFindings(
    interview: SupportInterview,
    now: Date,
): Finding[] {
    if (interview.status === 'not_started') {
        return [
            {
                id: 'interview-none',
                tone: 'waiting',
                title: 'No interview on file',
                detail:
                    'They have never started the Work Style Interview. Nothing downstream ' +
                    'can exist yet — no profile, no guide, no inferred skills.',
                owner: 'them',
            },
        ];
    }

    const out: Finding[] = [];
    const idle = daysSince(interview.last_activity_at, now);

    if (interview.status === 'abandoned') {
        out.push({
            id: 'interview-abandoned',
            tone: 'waiting',
            title: 'Interview abandoned',
            detail:
                `They walked away from this attempt (last touched ${agoLabel(idle)}). ` +
                'Starting again is theirs to do, and it does not delete anything.',
            owner: 'them',
        });
        return out;
    }

    if (interview.status === 'in_progress') {
        const { percent, sections_done, sections_total } = interview.progress;
        const stalled = idle !== null && idle >= STALLED_AFTER_DAYS;
        out.push({
            id: 'interview-in-progress',
            tone: stalled ? 'attention' : 'waiting',
            title: stalled ? 'Part-way through, and stalled' : 'Part-way through the interview',
            detail:
                `${Math.round(percent)}% done — ${sections_done} of ${sections_total} sections, ` +
                `last answered ${agoLabel(idle)}. ` +
                (stalled
                    ? 'Long enough that they have probably forgotten it is open. Their answers are safe; they resume where they stopped.'
                    : 'They resume at the item they stopped on.'),
            owner: 'them',
        });
        return out;
    }

    // Completed. The one genuine break this screen exists to catch.
    const scoredAge = daysSince(interview.completed_at, now);
    if (!interview.profile) {
        out.push({
            id: 'interview-unscored',
            tone: 'blocked',
            title: 'Finished, but never scored',
            detail:
                `They completed the interview ${agoLabel(scoredAge)} and there is still no ` +
                'profile. The scoring job was dispatched and never wrote back. There is no ' +
                'failure column on the interview row, so nothing will report this as an ' +
                'error and nothing will retry it on its own — check the cubie-worker logs ' +
                'for the run. Everything downstream is blocked behind it.',
            owner: 'system',
        });
        return out;
    }

    out.push({
        id: 'interview-scored',
        tone: 'ok',
        title: `Scored — profile version ${interview.profile.version}`,
        detail:
            `Completed ${agoLabel(scoredAge)}, scored from ${interview.profile.origin}. ` +
            `Status ${interview.profile.status}.`,
        owner: null,
    });
    return out;
}

function guideFindings(
    guides: GuideDocument[],
    hasProfile: boolean,
    now: Date,
): Finding[] {
    const out: Finding[] = [];
    const guide = currentGuide(guides);

    if (!guide) {
        if (hasProfile) {
            out.push({
                id: 'guide-none',
                tone: 'waiting',
                title: 'No guide generated yet',
                detail:
                    'They are scored, so they can generate one whenever they like. Nobody ' +
                    'can generate it for them — there is no subject parameter on that route.',
                owner: 'them',
            });
        }
        return out;
    }

    const age = daysSince(guide.updated_at ?? guide.created_at, now);

    if (guide.status === 'failed') {
        out.push({
            id: 'guide-failed',
            tone: 'blocked',
            title: 'Guide generation failed',
            detail: guide.error
                ? `The row carries its own reason: “${guide.error}” (${agoLabel(age)}).`
                : `It failed ${agoLabel(age)} and wrote no reason, which is itself worth chasing in the worker logs.`,
            owner: 'system',
        });
    } else if (guide.status === 'pending') {
        const stuck = age !== null && age >= STUCK_AFTER_DAYS;
        out.push({
            id: 'guide-pending',
            tone: stuck ? 'blocked' : 'waiting',
            title: stuck ? 'Guide has been generating for too long' : 'Guide is being written',
            detail: stuck
                ? `Dispatched ${agoLabel(age)} and still pending. A guide row has no “running” ` +
                  'state and no timeout: a job that died leaves it pending forever, so this ' +
                  'will not resolve itself. Check the worker run, then have them regenerate.'
                : `Dispatched ${agoLabel(age)}. Give it a few minutes before treating it as stuck.`,
            owner: 'system',
        });
    } else if (!guide.published) {
        out.push({
            id: 'guide-unapproved',
            tone: 'waiting',
            title: 'Guide is written, waiting on them to approve it',
            detail:
                'It is ready and only they can see it. Approving is what publishes it, and ' +
                'that is consent — a support admin gets a 403 on that route deliberately.',
            owner: 'them',
        });
    }

    if (guide.stale) {
        out.push({
            id: 'guide-stale',
            tone: 'attention',
            title: 'Guide is older than their profile',
            detail:
                `Written from profile version ${guide.profile_version ?? '—'}, and they are ` +
                `now on ${guide.current_profile_version ?? '—'}. Regenerating is theirs to do.`,
            owner: 'them',
        });
    }

    // The known purge gap, said out loud. An unpublished guide that is still
    // ingested is answerable in Chat after its subject retracted consent, and
    // this is the only screen where anybody would ever see it.
    if (!guide.published && guide.rag_ingested) {
        out.push({
            id: 'guide-ingested-unpublished',
            tone: 'blocked',
            title: 'Unpublished, but still in the Chat corpus',
            detail:
                'They retracted this guide and its vectors were never purged, so Cubie Chat ' +
                'can still quote it. This is the one finding here that is a live privacy ' +
                'problem rather than a stuck job — the purge has to be run against both ' +
                'corpora, not one.',
            owner: 'support',
        });
    }

    return out;
}

function uploadFindings(uploads: UploadRecord[], now: Date): Finding[] {
    const out: Finding[] = [];

    for (const upload of uploads) {
        if (upload.parse_error) {
            out.push({
                id: `upload-parse-${upload.id}`,
                tone: 'attention',
                title: `Could not read ${upload.original_filename}`,
                detail: `${upload.parse_error} (uploaded ${agoLabel(daysSince(upload.uploaded_at, now))}).`,
                owner: 'system',
            });
            continue;
        }
        if (upload.review_status === 'pending' && upload.mergeable) {
            out.push({
                id: `upload-pending-${upload.id}`,
                tone: 'waiting',
                title: `${upload.original_filename} is waiting on them`,
                detail:
                    'Cubie read it and is holding the proposal until they confirm. Support ' +
                    'cannot confirm it for them — a merge changes their profile, so it is consent.',
                owner: 'them',
            });
        }
    }

    return out;
}

const TONE_ORDER: Record<FindingTone, number> = {
    blocked: 0,
    attention: 1,
    waiting: 2,
    ok: 3,
};

/** Everything worth saying about one person, worst first.
 *
 *  Stable within a tone: findings keep the order the rules produced them, so the
 *  interview line stays above the guide line that depends on it. */
export function diagnose(input: DiagnosisInput): Finding[] {
    const { interview, guides, uploads, pendingSuggestions, now } = input;
    const out: Finding[] = [];

    if (interview) out.push(...interviewFindings(interview, now));

    const hasProfile =
        !!interview && interview.status !== 'not_started' && !!interview.profile;

    // Only diagnose a guide once there is something to generate one FROM.
    // "No guide yet" under "never started the interview" is noise dressed as a
    // finding, and three of those push the one real problem off the top.
    if (guides && (hasProfile || guides.length > 0)) {
        out.push(...guideFindings(guides, hasProfile, now));
    }
    if (uploads) out.push(...uploadFindings(uploads, now));

    if (pendingSuggestions && pendingSuggestions > 0) {
        out.push({
            id: 'skills-pending',
            tone: 'waiting',
            title: `${pendingSuggestions} skill ${pendingSuggestions === 1 ? 'suggestion' : 'suggestions'} unanswered`,
            detail:
                'Cubie suggested these and they have not said yes or no. Unanswered ' +
                'suggestions are invisible to everyone else, so nothing is staffing off them.',
            owner: 'them',
        });
    }

    return out
        .map((finding, index) => ({ finding, index }))
        .sort((a, b) =>
            TONE_ORDER[a.finding.tone] - TONE_ORDER[b.finding.tone] || a.index - b.index,
        )
        .map(({ finding }) => finding);
}

/** The one-line verdict for the top of the page. */
export function headline(findings: Finding[]): { tone: FindingTone; text: string } {
    const blocked = findings.filter(f => f.tone === 'blocked').length;
    if (blocked > 0) {
        return {
            tone: 'blocked',
            text:
                blocked === 1
                    ? 'One thing is broken and will not fix itself.'
                    : `${blocked} things are broken and will not fix themselves.`,
        };
    }
    if (findings.some(f => f.tone === 'attention')) {
        return { tone: 'attention', text: 'Nothing is broken, but something is worth a look.' };
    }
    if (findings.some(f => f.tone === 'waiting')) {
        return { tone: 'waiting', text: 'Nothing is broken — the system is waiting on a person.' };
    }
    return { tone: 'ok', text: 'Everything here is in order.' };
}
