"""Cubie-generated documents: persistence, Assets registration, sharing, drafts.

The product loop: a user turns a Meeting Prep brief or
Customer X-Ray into an editable Word doc, saves it to *their* Assets page, and
from there either shares it with a teammate (in-app grant + notification)
or has Cubie draft — never send — a Gmail message with the doc attached.

Design decisions that live here:

* **Generated docs never enter the RAG.** They are AI *output*; ingesting them
  would let Cubie cite its own prior answers as ground truth (circular
  grounding). So ``save_generated_doc`` registers the Asset row and stores the
  bytes, but deliberately skips the FileProcessor/vector pipeline. Rows carry
  the ``ASSET_TAG_GENERATED`` tag so the assets router knows archive/delete must
  not expect chunks in the corpus.

* **Sharing rides the existing ACL.** ``has_document_access`` rule 4 already
  honors ``Asset.allowed_emails``; a share is just an append there, plus an
  in-app Notification (always) and a best-effort link email (subject to the
  ``CUBIE_DEEP_PREP_EMAIL_AUTOSEND`` kill switch, like every system send).

* **Outbound email is draft-only.** Mirrors chat: ``GmailClient.create_draft``
  under the user's own mailbox, returns the Gmail URL for the UI to open. The
  send stays a human act.
"""

from __future__ import annotations

import hashlib
import html
import logging
import re
import uuid
from datetime import datetime
from pathlib import Path
from typing import Any

from rubik_core.brand import PRODUCT_NAME
from rubik_core.config import AppMode, settings
from rubik_core.dam.audit import log_action
from rubik_core.dam.registry import AssetMetadata, DAMRegistry
from rubik_core.database.db import SessionLocal
from rubik_core.database.models import Notification
from rubik_core.identifiers import ASSET_TAG_GENERATED
from rubik_core.tenancy.storage import assert_own_uri, local_data_dir, object_name

logger = logging.getLogger(__name__)

DOCX_MIME = "application/vnd.openxmlformats-officedocument.wordprocessingml.document"

#: Prefix of a generated doc's ``doc_id``. Brand-neutral on purpose: a stored id
#: outlives the product's name. ``smart_teams.uploads`` uses its own prefix.
DOC_ID_PREFIX = "gendoc-"
XRAY_DOC_ID_PREFIX = "xraydoc-"
XRAY_COMPANY_TAG_PREFIX = "xray-company:"
MEETING_PREP_RUN_TAG_PREFIX = "prep-run:"
MEETING_PREP_WORKSPACE_TAG_PREFIX = "prep-workspace:"
_COMPANY_ID = re.compile(r"[A-Za-z0-9_-]{1,128}\Z")

_registry = DAMRegistry()


def _gcs_blob_name(doc_id: str, filename: str) -> str:
    ext = Path(filename).suffix or ".docx"
    return object_name("generated-docs", f"{doc_id}{ext}")


def store_doc_bytes(doc_id: str, filename: str, data: bytes) -> str:
    """Persist generated bytes; return the recorded ``source_path``.

    GCP mode → the RAG bucket under the standard prefix (same bucket the DAM
    already uses, so IAM/lifecycle stay one story). Local mode → LOCAL_DATA_DIR.
    """
    blob_name = _gcs_blob_name(doc_id, filename)
    if settings.APP_MODE == AppMode.GCP:
        from google.cloud import storage

        client = storage.Client(project=settings.GCP_PROJECT_ID)
        blob = client.bucket(settings.GCS_BUCKET_NAME).blob(blob_name)
        blob.upload_from_string(data, content_type=DOCX_MIME)
        return f"gs://{settings.GCS_BUCKET_NAME}/{blob_name}"

    local_dir = local_data_dir() / "generated-docs"
    local_dir.mkdir(parents=True, exist_ok=True)
    path = local_dir / blob_name.rsplit("/", 1)[-1]
    path.write_bytes(data)
    return path.as_uri()


def load_doc_bytes(source_path: str) -> bytes:
    """Read stored bytes back from a ``gs://`` URI or a local path."""
    checked = assert_own_uri(source_path)
    if source_path.startswith("gs://"):
        from google.cloud import storage

        bucket_name, _, blob_name = checked[len("gs://") :].partition("/")
        client = storage.Client(project=settings.GCP_PROJECT_ID)
        return client.bucket(bucket_name).blob(blob_name).download_as_bytes()
    return Path(checked).read_bytes()


def delete_doc_bytes(source_path: str | None) -> None:
    """Best-effort removal of the stored object (delete/cleanup paths)."""
    if not source_path:
        return
    checked = assert_own_uri(source_path)
    try:
        if source_path.startswith("gs://"):
            from google.cloud import storage

            bucket_name, _, blob_name = checked[len("gs://") :].partition("/")
            client = storage.Client(project=settings.GCP_PROJECT_ID)
            client.bucket(bucket_name).blob(blob_name).delete()
        else:
            Path(checked).unlink(missing_ok=True)
    except Exception:  # noqa: BLE001 — cleanup must never block the operation
        logger.warning(
            "generated_docs: could not delete %s", source_path, exc_info=True
        )


def is_generated_asset(asset: Any) -> bool:
    return ASSET_TAG_GENERATED in (getattr(asset, "tags", None) or [])


def save_generated_doc(
    user_email: str,
    *,
    title: str,
    filename: str,
    data: bytes,
    kind: str,
    department: str | None = None,
    source_company_id: str | None = None,
    source_prep_run_id: str | None = None,
) -> tuple[AssetMetadata, bool]:
    """Store bytes + register the Asset row (NO RAG ingestion — see module doc).

    Returns ``(asset, created)`` — ``created=False`` means the identical bytes
    were already saved by this user (content-hash dedup), so a double-click
    can't litter the Assets page.
    """
    if kind == "customer-xray":
        if not source_company_id or not _COMPANY_ID.fullmatch(source_company_id):
            raise ValueError("X-Ray company ID is required for a saved document")
        if source_prep_run_id is not None:
            raise ValueError("Meeting Prep provenance is only valid for Meeting Prep")
    elif kind == "meeting-prep":
        if not source_prep_run_id or not _COMPANY_ID.fullmatch(source_prep_run_id):
            raise ValueError("Meeting Prep run ID is required for a saved document")
        if source_company_id is not None:
            raise ValueError("Company provenance is only valid for X-Ray documents")
    elif source_company_id is not None:
        raise ValueError("Company provenance is only valid for X-Ray documents")
    elif source_prep_run_id is not None:
        raise ValueError("Meeting Prep provenance is only valid for Meeting Prep")
    provenance_tag = (
        f"{XRAY_COMPANY_TAG_PREFIX}{source_company_id}" if source_company_id else None
    )
    prep_tags: list[str] = []
    if source_prep_run_id:
        from rubik_core.tenancy.context import current_workspace

        prep_tags = [
            f"{MEETING_PREP_RUN_TAG_PREFIX}{source_prep_run_id}",
            f"{MEETING_PREP_WORKSPACE_TAG_PREFIX}{current_workspace()}",
        ]
    content_hash = hashlib.sha256(data).hexdigest()
    existing = _registry.get_asset_by_content_hash(content_hash)
    if (
        existing is not None
        and existing.owner == user_email
        and (provenance_tag is None or provenance_tag in (existing.tags or []))
        and all(tag in (existing.tags or []) for tag in prep_tags)
        and kind in (existing.tags or [])
    ):
        return existing, False

    prefix = XRAY_DOC_ID_PREFIX if kind == "customer-xray" else DOC_ID_PREFIX
    doc_id = f"{prefix}{uuid.uuid4().hex[:16]}"
    source_path = store_doc_bytes(doc_id, filename, data)
    now = datetime.utcnow()
    topic = {"meeting-prep": "Meeting Prep", "customer-xray": "Customer X-Ray"}.get(
        kind, f"{PRODUCT_NAME} Docs"
    )
    asset = AssetMetadata(
        doc_id=doc_id,
        owner=user_email,
        # Live immediately as a *record* — but with no chunks it is invisible
        # to Chat retrieval, which is exactly the point.
        status="approved",
        topic=topic,
        department=department,
        description=f"{PRODUCT_NAME}-generated {topic} document: {title}",
        tags=[
            ASSET_TAG_GENERATED,
            kind,
            *([provenance_tag] if provenance_tag else []),
            *prep_tags,
        ],
        original_filename=filename,
        source_path=source_path,
        is_company_wide=False,
        allowed_emails=[],
        content_hash=content_hash,
        processing=False,
        created_at=now,
        updated_at=now,
    )
    _registry.register_asset(asset)
    log_action(user_email, "generated_doc.save", doc_id, "success", {"kind": kind})
    return asset, True


def _notify(recipient: str, *, title: str, body: str, link: str) -> None:
    db = SessionLocal()
    try:
        db.add(
            Notification(
                id=str(uuid.uuid4()),
                actor_email=recipient,
                kind="asset_shared",
                title=title,
                body=body,
                severity="info",
                link=link,
            )
        )
        db.commit()
    except Exception:  # noqa: BLE001 — notification is a courtesy, not a contract
        db.rollback()
        logger.exception("generated_docs: notification insert failed for %s", recipient)
    finally:
        db.close()


def share_asset(
    sharer_email: str,
    asset: AssetMetadata,
    emails: list[str],
) -> dict[str, Any]:
    """Grant teammates read access + notify them. Returns the outcome summary.

    Internal only: recipients must be on a verified workspace domain (client data
    never leaves via this path — external delivery is the human-owned Gmail
    draft). With no domain configured nobody can be added.
    """
    from rubik_core.company.domain import workspace_domains

    domains = workspace_domains()
    if not domains:
        raise ValueError(
            "Sharing is unavailable: this workspace has no verified domain."
        )
    cleaned: list[str] = []
    rejected: list[str] = []
    for raw in emails:
        e = (raw or "").strip().lower()
        if not e or e == sharer_email.lower() or e in cleaned:
            continue
        if e.rsplit("@", 1)[-1] not in domains:
            rejected.append(e)
            continue
        cleaned.append(e)
    if rejected:
        raise ValueError(
            "Only teammates on a verified workspace domain can be added: "
            + ", ".join(rejected)
        )

    current = list(asset.allowed_emails or [])
    added = [e for e in cleaned if e not in current]
    if added:
        _registry.update_asset(asset.doc_id, {"allowed_emails": current + added})

    doc_name = asset.original_filename or asset.doc_id
    link = "/assets"
    for recipient in added:
        _notify(
            recipient,
            title=f"{sharer_email} shared a document with you",
            body=f'"{doc_name}" is now available on your Assets page.',
            link=link,
        )

    # Best-effort email with the Cubie link. Rides the system-send rails, so the
    # CUBIE_DEEP_PREP_EMAIL_AUTOSEND kill switch applies (dark → bell only).
    email_status = "skipped"
    if added:
        try:
            from rubik_core.company.operations import get_operations_config
            from rubik_core.tools.email_sender import EmailMessageSpec, send_email

            url = f"{settings.FRONTEND_URL.rstrip('/')}/assets"
            result = send_email(
                EmailMessageSpec(
                    to=added,
                    subject=f"{sharer_email} shared “{doc_name}” with you in {PRODUCT_NAME}",
                    text_body=(
                        f"{sharer_email} shared “{doc_name}” with you.\n\n"
                        f"Open your Assets page in {PRODUCT_NAME} to view or download it:\n{url}\n"
                    ),
                    html_body=(
                        '<div style="font-family:-apple-system,Segoe UI,sans-serif;'
                        'max-width:560px">'
                        f"<p><strong>{html.escape(sharer_email)}</strong> shared "
                        f"<strong>{html.escape(doc_name)}</strong> with you.</p>"
                        f'<p><a href="{html.escape(url)}">Open your Assets page '
                        f"in {PRODUCT_NAME}</a> "
                        "to view or download it.</p></div>"
                    ),
                ),
                impersonate=(
                    get_operations_config().deep_prep_sender_mailbox or sharer_email
                ),
            )
            email_status = result.status
        except Exception:  # noqa: BLE001
            logger.exception("generated_docs: share email failed")
            email_status = "failed"

    log_action(
        sharer_email,
        "generated_doc.share",
        asset.doc_id,
        "success",
        {"added": added, "email_status": email_status},
    )
    return {
        "shared_with": added,
        "already_had_access": [e for e in cleaned if e not in added],
        "email_status": email_status,
    }


def create_asset_email_draft(
    user_email: str,
    asset: AssetMetadata,
    *,
    to: list[str] | None = None,
    note: str = "",
) -> dict[str, Any]:
    """Draft (never send) a Gmail message in the user's mailbox with the doc
    attached; returns ``{draft_id, gmail_draft_url}`` for the UI to open."""
    from rubik_core.tools.gmail import GmailClient

    data = load_doc_bytes(asset.source_path or "")
    filename = asset.original_filename or f"{asset.doc_id}.docx"
    subject = (
        Path(filename).stem.replace("-", " ").strip() or f"Document from {PRODUCT_NAME}"
    )
    body = note.strip() or (
        f"Hi,\n\nSharing “{Path(filename).stem}” ahead of our call — "
        f"attached.\n\n(Prepared with {PRODUCT_NAME}.)"
    )
    result = GmailClient(user_email).create_draft(
        to=[e.strip() for e in (to or []) if e and e.strip()],
        subject=subject,
        body_markdown=body,
        attachments=[(filename, DOCX_MIME, data)],
    )
    log_action(user_email, "generated_doc.email_draft", asset.doc_id, "success")
    return result
